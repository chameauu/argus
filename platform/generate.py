#!/usr/bin/env python3
"""Render the argus platform artefacts from service descriptors.

Every per-service output is derived from ``services/<name>.yaml`` through a
``string.Template`` in ``platform/templates/``. The descriptor parser and
validator are reused from ``contract_check.py``; this module does not carry a
second YAML reader.

Generated:
  docker-compose/configs/prometheus/prometheus.yml   whole file
  alert-rules/generated/red-<name>.yml                RED rules
  alert-rules/generated/slo-<name>.yml                Sloth SLO rules
  runbooks/generated/<name>.md                        runbook stub
  dashboards/generated/red-<name>.json                per-service RED dashboard

The SLO rules are produced by running the pinned Sloth image over a spec
rendered from the descriptor. Sloth's ``validate`` runs as a gate before
``generate``; if Docker is unavailable the whole run fails instead of quietly
skipping the SLO artefacts.

``dashboards/generated/slo-overview.json`` is vendored from Grafana.com (see
``dashboards/generated/README.md``), not rendered here.

Usage:
  python3 platform/generate.py [--services-dir services] [--out .] [--check]

``--check`` renders into a temporary directory and compares bytes with the
tree. Exit 0 means no drift; exit 1 prints a per-file summary (including a
build-based compose service with no descriptor). An unparseable or invalid
descriptor is reported and skipped: the remaining services still render, and
the run exits 2 so the broken file cannot pass silently.

Standard library only. Output is deterministic: sorted services, LF endings,
no timestamps, no absolute paths. Sloth's output embeds only its build hash,
which the pinned digest fixes.
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from string import Template

from contract_check import YamlError, parse_descriptor, validate_descriptor

PLATFORM_DIR = Path(__file__).resolve().parent
TEMPLATE_DIR = PLATFORM_DIR / "templates"

PROMETHEUS_OUTPUT = "docker-compose/configs/prometheus/prometheus.yml"
RULES_DIR = "alert-rules/generated"
RUNBOOKS_DIR = "runbooks/generated"
DASHBOARDS_DIR = "dashboards/generated"

# Pinned by digest: docker.io and ghcr.io publish no semver tags for Sloth.
SLOTH_IMAGE = "slok/sloth@sha256:556583d62003ef4d7599d97385f7097bf5aa9ab2c68a550bc60de2e22c06c0a7"
SLOTH_SPEC_IN_CONTAINER = "/spec/spec.yml"
SLOTH_TIMEOUT_S = 180

# Generated files carry a marker so the generator only ever deletes artefacts
# it can prove it wrote. The name pattern and marker are checked together: a
# hand-authored file that merely happens to match the naming scheme survives.
GENERATED_FILE_PATTERNS = {
    RULES_DIR: re.compile(r"^(?:red|slo)-[A-Za-z0-9._-]+\.yml$"),
    RUNBOOKS_DIR: re.compile(r"^[A-Za-z0-9._-]+\.md$"),
    DASHBOARDS_DIR: re.compile(r"^red-[A-Za-z0-9._-]+\.json$"),
}
GENERATED_FILE_MARKERS = {
    RULES_DIR: ("# Generated by platform/generate.py", "# Code generated by Sloth"),
    RUNBOOKS_DIR: ("_Generated from `services/",),
    DASHBOARDS_DIR: ('"tags": ["argus", "red", "generated"]',),
}

# Keep the rendered scrape_configs stable across runs.
NAME_PART_RE = re.compile(r"[-_.]+")

# The compose service block is still hand-edited, so --check treats a
# build-based compose service with no descriptor as drift. Names here are the
# genuinely platform-owned services; custom-exporter and webhook-receiver are
# application services (they have descriptors), so they are intentionally
# absent and deleting either descriptor must surface as drift.
COMPOSE_FILE = "docker-compose/docker-compose.yml"
PLATFORM_COMPOSE_SERVICES = frozenset(
    {
        "prometheus",
        "loki",
        "grafana",
        "tempo",
        "alertmanager",
        "alloy",
        "otel-collector",
        "node-exporter",
        "cadvisor",
        "load-generator",
    }
)
COMPOSE_SERVICE_RE = re.compile(r"^ {2}([A-Za-z0-9][A-Za-z0-9._-]*):\s*(?:#.*)?$")
COMPOSE_BUILD_RE = re.compile(r"^ {4}build:")
COMPOSE_SERVICES_RE = re.compile(r"^services:\s*(?:#.*)?$")


class GenerateError(RuntimeError):
    """A descriptor or template is unusable; the run must fail loudly."""


def read_template(name):
    try:
        return Template((TEMPLATE_DIR / name).read_text(encoding="utf-8"))
    except OSError as exc:
        raise GenerateError(f"template {name}: {exc}") from exc


def pascal_case(name):
    return "".join(part[:1].upper() + part[1:] for part in NAME_PART_RE.split(name) if part)


def format_number(value):
    return f"{value:g}"


def format_percent(value):
    return f"{value * 100:g}%"


def load_services(services_dir):
    """Parse and validate every descriptor, isolating per-file failures.

    Returns ``(valid_services, errors)``: one bad descriptor is reported but
    does not prevent the remaining services from rendering.
    """
    directory = Path(services_dir)
    paths = sorted(directory.glob("*.yaml"))
    if not paths:
        raise GenerateError(f"no descriptors in {directory}")
    services = []
    errors = []
    for path in paths:
        name = path.stem
        try:
            data = parse_descriptor(path.read_text(encoding="utf-8"))
        except (OSError, YamlError) as exc:
            errors.append(f"{path}: unparseable: {exc}")
            continue
        problems = validate_descriptor(data, name)
        if problems:
            details = "; ".join(problems[:8])
            if len(problems) > 8:
                details += f"; … (+{len(problems) - 8} more)"
            errors.append(f"{path}: invalid descriptor: {details}")
            continue
        services.append((name, data))
    return services, errors


def format_objective(value):
    """0.995 -> "99.5": Sloth wants the objective as a percentage number."""
    return f"{value * 100:g}"


def routes_regex(routes):
    """Turn an allowlist into a PromQL regex alternation.

    Prometheus regex matchers are fully anchored, so no anchors are needed.
    Backslash-escaped hyphens are valid RE2 but needlessly noisy; keep them as
    literal hyphens for readable generated rules.

    The alternation is embedded in a double-quoted PromQL string, where `\\{`
    is an invalid escape; every backslash the regex needs must be doubled so
    PromQL decodes it back to the single backslash RE2 expects. Without this a
    contract-legal route template such as `/orders/{id}` fails Sloth's
    `prom_expr` validation.
    """
    alternation = "|".join(re.escape(route).replace("\\-", "-") for route in routes)
    return alternation.replace("\\", "\\\\")


def service_context(name, data):
    scrape = data["scrape"]
    health = data["health"]
    slos = data["slos"]
    availability = slos["availability"]
    latency = slos["latency"]
    metrics = data.get("metrics") or {}
    routes = data["routes_allowlist"]
    route_label = metrics.get("route_label", "route")
    threshold = format_number(latency["threshold_seconds"])
    histogram = latency["histogram"]
    pascal = pascal_case(name)
    return {
        "name": name,
        "owner": data["owner"],
        "namespace": data["namespace"],
        "environment": data["environment"],
        "target": f"{name}:{scrape['port']}",
        "metrics_path": scrape.get("path", "/metrics"),
        "interval": scrape.get("interval", "15s"),
        "health_path": health.get("path", "/healthz"),
        "route_count": str(len(routes)),
        "routes": ", ".join(f"`{route}`" for route in routes) or "none",
        "routes_regex": routes_regex(routes),
        "availability_objective": format_percent(availability["objective"]),
        "availability_objective_pct": format_objective(availability["objective"]),
        "availability_window": availability["window"],
        "error_selector": availability["error_selector"],
        "latency_objective": format_percent(latency["objective"]),
        "latency_objective_pct": format_objective(latency["objective"]),
        "threshold": threshold,
        "threshold_seconds": threshold,
        "route_label": route_label,
        "route_legend": "{{" + route_label + "}}",
        "requests_metric": metrics.get("requests_total", "not declared"),
        "latency_metric": histogram,
        "latency_histogram": histogram,
        "latency_bucket": f"{histogram}_bucket",
        "down_alert": f"{pascal}Down",
        "error_alert": f"{pascal}HighErrorRate",
        "latency_alert": f"{pascal}HighLatency",
        # Alert names are not templated by Sloth: embed the service name so two
        # descriptors with the same SLO names cannot collapse into one alert.
        "availability_slo_alert": f"{pascal}AvailabilityBurnRate",
        "latency_slo_alert": f"{pascal}LatencyBurnRate",
        "generated_runbook": f"{RUNBOOKS_DIR}/{name}.md",
    }


def render_app_job(context):
    return read_template("app-job.yml.tmpl").substitute(context).rstrip("\n")


def render_prometheus(services):
    jobs = [
        render_app_job(service_context(name, data))
        for name, data in sorted(services, key=lambda item: item[0])
    ]
    body = read_template("prometheus.yml.tmpl").substitute(app_jobs="\n\n".join(jobs))
    return body.rstrip("\n") + "\n"


def render_rules(name, data):
    context = service_context(name, data)
    template = "red-rules.yml.tmpl" if data.get("metrics") else "red-down.yml.tmpl"
    body = read_template(template).substitute(context)
    return body.rstrip("\n") + "\n"


def render_runbook(name, data):
    body = read_template("runbook.md.tmpl").substitute(service_context(name, data))
    return body.rstrip("\n") + "\n"


def ensure_docker():
    """Fail loudly when Docker is unavailable: SLO artefacts must not be skipped."""
    if shutil.which("docker") is None:
        raise GenerateError(
            "docker not found on PATH; Sloth needs Docker to render alert-rules/generated/slo-*.yml"
        )
    try:
        probe = subprocess.run(
            ["docker", "version", "--format", "{{.Server.Version}}"],
            capture_output=True,
            text=True,
            timeout=30,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise GenerateError(f"docker is not usable: {type(exc).__name__}: {exc}") from exc
    if probe.returncode != 0:
        detail = (probe.stderr or probe.stdout).strip().splitlines()
        reason = detail[-1] if detail else f"exit {probe.returncode}"
        raise GenerateError(f"docker is not usable: {reason}")


def run_sloth(args, spec_text):
    """Run the pinned Sloth image; return (stdout, stderr, returncode)."""
    try:
        completed = subprocess.run(
            ["docker", "run", "--rm", "-i", SLOTH_IMAGE, *args],
            input=spec_text,
            capture_output=True,
            text=True,
            timeout=SLOTH_TIMEOUT_S,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise GenerateError(f"sloth {args[0]} failed to run: {type(exc).__name__}: {exc}") from exc
    return completed.stdout, completed.stderr, completed.returncode


def sloth_generate(name, data):
    """Render the spec, validate it, generate rules. Returns Sloth's YAML output."""
    context = service_context(name, data)
    spec = read_template("sloth-spec.yml.tmpl").substitute(context).rstrip("\n") + "\n"

    # `validate` needs a real file path; the container is non-root and `-o` to a
    # host mount fails, so bind-mount a 0644 temp file read-only instead.
    with tempfile.TemporaryDirectory(prefix="argus-sloth-") as temp_dir:
        spec_path = Path(temp_dir) / "spec.yml"
        spec_path.write_text(spec, encoding="utf-8")
        spec_path.chmod(0o644)
        try:
            validate = subprocess.run(
                [
                    "docker",
                    "run",
                    "--rm",
                    "-v",
                    f"{spec_path}:{SLOTH_SPEC_IN_CONTAINER}:ro",
                    SLOTH_IMAGE,
                    "validate",
                    "-i",
                    SLOTH_SPEC_IN_CONTAINER,
                ],
                capture_output=True,
                text=True,
                timeout=SLOTH_TIMEOUT_S,
                check=False,
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise GenerateError(
                f"{name}: sloth validate failed: {type(exc).__name__}: {exc}"
            ) from exc
        if validate.returncode != 0 or "Validation succeeded" not in (
            validate.stdout + validate.stderr
        ):
            detail = (validate.stdout + validate.stderr).strip().splitlines()
            reason = detail[-1] if detail else f"exit {validate.returncode}"
            raise GenerateError(f"{name}: sloth rejected the generated spec: {reason}")

    stdout, stderr, returncode = run_sloth(["generate", "-i", "/dev/stdin"], spec)
    if returncode != 0:
        detail = (stdout + stderr).strip().splitlines()
        reason = detail[-1] if detail else f"exit {returncode}"
        raise GenerateError(f"{name}: sloth generate failed: {reason}")
    if "Code generated by Sloth" not in stdout:
        raise GenerateError(f"{name}: sloth generated no rule file")
    return stdout if stdout.endswith("\n") else stdout + "\n"


def render_slo_rules(name, data):
    return sloth_generate(name, data)


def render_red_dashboard(name, data):
    context = service_context(name, data)
    body = read_template("red-dashboard.json.tmpl").substitute(context)
    # Fail here rather than in Grafana if a substituted value broke the JSON.
    try:
        json.loads(body)
    except ValueError as exc:
        raise GenerateError(f"{name}: rendered dashboard is not valid JSON: {exc}") from exc
    return body.rstrip("\n") + "\n"


def render_all(services):
    rendered = {PROMETHEUS_OUTPUT: render_prometheus(services)}
    needs_sloth = any(data.get("metrics") for _, data in services)
    if needs_sloth:
        ensure_docker()
    for name, data in services:
        rendered[f"{RULES_DIR}/red-{name}.yml"] = render_rules(name, data)
        rendered[f"{RUNBOOKS_DIR}/{name}.md"] = render_runbook(name, data)
        if data.get("metrics"):
            rendered[f"{RULES_DIR}/slo-{name}.yml"] = render_slo_rules(name, data)
            rendered[f"{DASHBOARDS_DIR}/red-{name}.json"] = render_red_dashboard(name, data)
    return dict(sorted(rendered.items()))


def is_generated_file(path, relative):
    """True only when the path matches the generated naming scheme *and* the
    file carries the marker the generator writes into that artefact type."""
    directory = str(Path(relative).parent)
    pattern = GENERATED_FILE_PATTERNS.get(directory)
    if pattern is None or not pattern.fullmatch(path.name):
        return False
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False
    return any(marker in text for marker in GENERATED_FILE_MARKERS[directory])


def generated_files(out_dir):
    """Relative paths of every artefact the generator can prove it owns."""
    root = Path(out_dir)
    owned = set()
    for relative_dir in GENERATED_FILE_PATTERNS:
        directory = root / relative_dir
        if not directory.is_dir():
            continue
        for path in sorted(directory.iterdir()):
            if not path.is_file():
                continue
            relative = f"{relative_dir}/{path.name}"
            if is_generated_file(path, relative):
                owned.add(relative)
    return owned


def remove_orphans(rendered, out_dir):
    """Delete owned artefacts whose service no longer has a descriptor.

    Generation writes every expected file first, so a failure cannot leave the
    tree with fewer artefacts than it started with. Only files matched by the
    naming scheme *and* the generated marker are removed.
    """
    root = Path(out_dir)
    expected = set(rendered)
    for relative in sorted(generated_files(root) - expected):
        try:
            (root / relative).unlink()
        except OSError as exc:
            raise GenerateError(f"cannot remove orphan {relative}: {exc}") from exc
        print(f"removed orphan {relative}")


def write_all(rendered, out_dir, prune=True):
    root = Path(out_dir)
    for relative, content in rendered.items():
        destination = root / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(content.encode("utf-8"))
        print(f"wrote {relative} ({len(content)} bytes)")
    if prune:
        remove_orphans(rendered, out_dir)


def compose_build_services(compose_path):
    """Names of ``build:``-based services in the compose ``services:`` block.

    A stdlib line scan is deliberate: the platform has no YAML dependency and
    only needs the service-name/build pairs, not the whole document.
    """
    path = Path(compose_path)
    if not path.is_file():
        return set()
    names = set()
    in_services = False
    current = None
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if not raw[0].isspace():
            in_services = bool(COMPOSE_SERVICES_RE.match(raw))
            current = None
            continue
        if not in_services:
            continue
        service = COMPOSE_SERVICE_RE.match(raw)
        if service:
            current = service.group(1)
            continue
        if current and COMPOSE_BUILD_RE.match(raw):
            names.add(current)
    return names


def compose_drift(services_dir, out_dir):
    """Build-based compose services that no longer have a descriptor."""
    described = {path.stem for path in Path(services_dir).glob("*.yaml")}
    drift = []
    for name in sorted(compose_build_services(Path(out_dir) / COMPOSE_FILE)):
        if name in described or name in PLATFORM_COMPOSE_SERVICES:
            continue
        drift.append(f"ORPHAN compose service {name} (no descriptor)")
    return drift


def diff_summary(relative, expected, actual):
    expected_lines = expected.splitlines()
    actual_lines = actual.splitlines()
    removed = sum(1 for line in actual_lines if line not in expected_lines)
    added = sum(1 for line in expected_lines if line not in actual_lines)
    return f"CHANGED {relative} (+{added}/-{removed} lines vs rendered)"


def check_all(temp_dir, out_dir, relative_paths, services_dir="services", check_orphans=True):
    temp_root = Path(temp_dir)
    root = Path(out_dir)
    drift = []
    for relative in relative_paths:
        expected = (temp_root / relative).read_text(encoding="utf-8")
        destination = root / relative
        if not destination.is_file():
            drift.append(f"MISSING {relative}")
            continue
        try:
            actual = destination.read_bytes().decode("utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            drift.append(f"UNREADABLE {relative}: {type(exc).__name__}")
            continue
        if actual != expected:
            drift.append(diff_summary(relative, expected, actual))
    # A descriptor that was deleted leaves generated artefacts behind. The
    # prometheus.yml rule_files glob would keep loading those rules, so an
    # orphan is drift even though no rendered file differs. When a descriptor
    # failed validation, its artefacts are not orphans: the service still
    # exists and pruning them would turn a typo into data loss.
    if check_orphans:
        for relative in sorted(generated_files(root) - set(relative_paths)):
            drift.append(f"ORPHAN {relative} (generated, no descriptor)")
    # The compose block is outside the generator, so a build-based app whose
    # descriptor was deleted would keep running and being scraped.
    drift.extend(compose_drift(services_dir, out_dir))
    if drift:
        print(f"generate: {len(drift)} drift item(s)")
        for line in drift:
            print(f"  {line}")
        return 1
    print(f"generate: no drift ({len(relative_paths)} files)")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Render argus platform artefacts from services/*.yaml descriptors."
    )
    parser.add_argument(
        "--services-dir", default="services", help="descriptor directory (default services)"
    )
    parser.add_argument("--out", default=".", help="output root (default .)")
    parser.add_argument(
        "--check",
        action="store_true",
        help="render to a temp dir and diff against --out; exit 1 on drift",
    )
    args = parser.parse_args(argv)

    try:
        services, errors = load_services(args.services_dir)
    except GenerateError as exc:
        print(f"generate: {exc}", file=sys.stderr)
        return 2

    for error in errors:
        print(f"generate: {error}", file=sys.stderr)
    if not services:
        print("generate: no valid descriptors; nothing rendered", file=sys.stderr)
        return 2
    if errors:
        print(
            f"generate: {len(errors)} invalid descriptor(s); "
            f"continuing with {len(services)} valid service(s)",
            file=sys.stderr,
        )

    try:
        rendered = render_all(services)
    except GenerateError as exc:
        print(f"generate: {exc}", file=sys.stderr)
        return 2

    if args.check:
        with tempfile.TemporaryDirectory(prefix="argus-generate-") as temp_dir:
            write_all_to_temp(rendered, temp_dir)
            status = check_all(
                temp_dir,
                args.out,
                rendered.keys(),
                services_dir=args.services_dir,
                check_orphans=not errors,
            )
        return 2 if errors else status

    write_all(rendered, args.out, prune=not errors)
    return 2 if errors else 0


def write_all_to_temp(rendered, temp_dir):
    """Materialise the render so --check can be self-tested if needed."""
    root = Path(temp_dir)
    for relative, content in rendered.items():
        destination = root / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(content.encode("utf-8"))


if __name__ == "__main__":
    sys.exit(main())
